"""Compare main, the working tree, and the working tree with FACTOR_SOS_PRE on
tests/benchmarks/lbp_stress.mpl (generated by tests/util/gen_lbp_stress.mpl).

Each variant times spCertificates with tests/benchmark_lbp_stress.mpl (60 s
limit per case) in fresh processes, with the fixed flags from `make -Bn`.
spCertificates is deterministic, so a case that times out in a variant's first
run is not rerun in later runs of that variant (recorded as a timeout). After
timing, every certificate is recomputed (60 s limit) and checked exactly.
"""
import argparse
from collections import Counter
import json
import os
from pathlib import Path
import re
import shlex
import statistics
import subprocess
import sys
import tempfile
import time

sys.dont_write_bytecode = True
from run_lower_bound_comparison import main_tree, verify
from run_arch_flag_benchmarking import hashes
from run_stage_division_benchmarking import ROOT

REPEATS = 7
TIMEOUT = 60
SUITE = "lbp_stress"


def parse(output, variant, repeat):
    if "LBP_STRESS_COMPLETE" not in output:
        raise RuntimeError("Benchmark did not finish")
    rows = []
    for block in output.split("\n>> Test\n")[1:]:
        label = re.match(r"Batch: (\d+) Test - Weifeng", block)
        if not label:
            raise RuntimeError("Unexpected benchmark test label")
        case = int(label[1])
        elapsed = re.search(r"^>> Time taken\n([0-9.]+)", block, re.M)
        if ">> Skipped after timeout" in block or ">> Timeout Weifeng" in block:
            status = "timeout"
        elif ">> Error Weifeng" in block:
            status = "error"
        elif elapsed:
            status = "success"
        else:
            raise RuntimeError(f"Missing result for case {case}")
        rows.append(dict(case=case, variant=variant, repeat=repeat, status=status,
                         cpu_seconds=float(elapsed[1]) if status == "success" and elapsed else None))
    cases = [r["case"] for r in rows]
    if cases != list(range(1, len(cases)+1)):
        raise RuntimeError("Missing benchmark cases")
    return rows


def write_report(data, dest):
    variants = list(data["variants"])
    rows = data["runs"]
    cases = sorted({r["case"] for r in rows})
    ver = {v: {c: data["verification"][v].get(f"{SUITE}:{c}") for c in cases} for v in variants}
    def values(case, v):
        return [r["cpu_seconds"] for r in rows
                if r["case"] == case and r["variant"] == v and r["status"] == "success"]
    def solved(case, v):
        return len(values(case, v)) == REPEATS
    def degree(case, v):
        info = ver[v][case]
        return info["max_degree"] if info and info["degrees"] else None
    common = [c for c in cases if all(solved(c, v) for v in variants)]
    totals = {v: sum(statistics.median(values(c, v)) for c in common) for v in variants}
    report = f"""# lower_bound_poly stress study: main vs working tree (± FACTOR_SOS_PRE)

Suite `tests/benchmarks/{SUITE}.mpl`: {len(cases)} cases generated by
`tests/util/gen_lbp_stress.mpl` (fixed seed). Each basis has at most 4 generators of
degree <= 3, always including an Archimedean generator R^2 - x^2, so the quadratic
module is Archimedean and every input (positive on S by construction, checked exactly)
is a member. Inputs have degree 3-7, above the bound polynomial's degree 2, and are
negative somewhere on R, so `lower_bound_poly`'s high-degree branch and Last_step are
reachable. `main` is `{data['main_ref']}` (its `src/` in a scratch tree next to a copy
of the working tree's `tests/`). Fixed Makefile flags for every variant:

```text
{data['make_command']}
```

Variants: {"; ".join(f"`{v}` adds `{' '.join(f) or 'nothing'}`" for v, f in data["variants"].items())}.

Time limit **{TIMEOUT} s per case** (`timelimit`, CPU time). {REPEATS} fresh-process runs per
variant in rotating order; a case that timed out in a variant's first run is recorded
as a timeout in its later runs without rerunning (spCertificates is deterministic).
Timings are CPU seconds printed by `checkWeifeng`. Degrees are **exact**: every
certificate was recomputed and expanded by `tests/verify_external_certificates.mpl`,
which also checks the identity and the nonnegativity of every multiplier.

## Summary

CPU time is the sum of per-case medians over the **{len(common)} cases** solved in every
run by every variant. Degree comparisons use cases where both versions produced a
certificate.

| Variant | Solved (≤ {TIMEOUT} s) | Timeouts | Errors | CPU time, common cases (s) | Change vs main | Valid certificates | Max degree vs main (lower / equal / higher) | Median max degree |
|---|---:|---:|---:|---:|---:|---:|---|---:|
"""
    for v in variants:
        statuses = Counter(next(r["status"] for r in rows if r["case"] == c and r["variant"] == v
                                and r["repeat"] == 1) for c in cases)
        valid = sum(1 for c in cases if ver[v][c] and ver[v][c]["valid"])
        unchecked = sum(1 for c in cases if ver[v][c] and ver[v][c]["status"] == "check_timeout")
        cmp = Counter()
        for c in cases:
            a, b = degree(c, "main"), degree(c, v)
            if a is not None and b is not None:
                cmp["lower" if b < a else "higher" if b > a else "equal"] += 1
        degs = [d for d in (degree(c, v) for c in cases) if d is not None]
        delta = 100*(totals[v]/totals["main"]-1) if totals["main"] else 0
        report += (f"| {v} | {statuses['success']}/{len(cases)} | {statuses['timeout']} | {statuses['error']} | "
                   f"{totals[v]:.3f} | {delta:+.1f}% | {valid}"
                   + (f" (+{unchecked} unchecked)" if unchecked else "") + " | "
                   + ("—" if v == "main" else f"{cmp['lower']} / {cmp['equal']} / {cmp['higher']}")
                   + f" | {statistics.median(degs) if degs else '—'} |\n")
    report += "\n## Per case\n\nEach cell: median CPU seconds (or TIMEOUT/ERROR); exact degrees of `[sigma_0, sigma_1, ...]`.\n\n"
    report += "| Case | deg f | #gens | " + " | ".join(variants) + " |\n|---:|---:|---:|" + "---|"*len(variants) + "\n"
    for c in cases:
        cells = []
        for v in variants:
            vals = values(c, v)
            first = next(r["status"] for r in rows if r["case"] == c and r["variant"] == v and r["repeat"] == 1)
            info = ver[v][c]
            cell = f"{statistics.median(vals):.3f}" if solved(c, v) else first.upper()
            if info and info["degrees"]:
                cell += f"; {info['degrees']}" + ("" if info["valid"] else
                                                 " (unchecked)" if info["valid"] is None else " INVALID")
            cells.append(cell)
        meta = data["inputs"][c-1]
        report += f"| {c} | {meta['degree']} | {meta['generators']} | " + " | ".join(cells) + " |\n"
    report += f"\nRaw data: `lbp_stress_comparison_runs.json`. Logs: `{data['log_directory']}`.\n"
    (dest / "lbp_stress_comparison.md").write_text(report)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--main-ref", default="main")
    args = parser.parse_args()
    build = subprocess.check_output(["make", "-Bn"], cwd=ROOT, text=True).strip()
    command = shlex.split(build)
    if len(build.splitlines()) != 1 or command[0] != "maple":
        raise RuntimeError("Unexpected Makefile command")
    fixed = command[1:-1]
    ref = subprocess.check_output(["git", "rev-parse", "--short", args.main_ref],
                                  cwd=ROOT, text=True).strip()
    variant_flags = {"main": [], "working_tree": [], "working_tree+FACTOR_SOS_PRE": ["-DFACTOR_SOS_PRE"]}
    roots = {"main": main_tree(ref), "working_tree": ROOT, "working_tree+FACTOR_SOS_PRE": ROOT}
    variants = list(variant_flags)
    with tempfile.NamedTemporaryFile("w", suffix=".mpl", delete=False) as script:
        script.write(f'read "tests/benchmarks/{SUITE}.mpl":\n'
                     'for b in external_benchmarks do printf("INPUT %d %d\\n", degree(b[1], x), nops(b[2])) end do:\n'
                     'quit:\n')
    inputs = subprocess.check_output(["maple", "-q", script.name], cwd=ROOT, text=True)
    inputs = [dict(degree=int(d), generators=int(n)) for d, n in re.findall(r"INPUT (\d+) (\d+)", inputs)]
    before = hashes()
    logdir = Path(tempfile.mkdtemp(prefix="lbp_stress_"))
    dest = ROOT / "tests/results"
    dest.mkdir(exist_ok=True)
    runs, verification = [], {}
    data = dict(make_command=build, fixed_flags=fixed, main_ref=ref, variants=variant_flags,
                repetitions=REPEATS, timeout=TIMEOUT, inputs=inputs, source_sha256=before,
                log_directory=str(logdir), runs=runs, verification=verification)
    timed_out = {v: set() for v in variants}
    for repeat in range(1, REPEATS+1):
        shift = (repeat-1) % len(variants)
        for variant in variants[shift:] + variants[:shift]:
            log = logdir / f"{variant}_{repeat}.log"
            started = time.monotonic()
            env = dict(os.environ, SKIP_CASES=",".join(map(str, sorted(timed_out[variant]))))
            with log.open("w") as stream:
                subprocess.run(["maple", "-q", *fixed, *variant_flags[variant],
                                "tests/benchmark_lbp_stress.mpl"],
                               cwd=roots[variant], stdout=stream, stderr=subprocess.STDOUT,
                               check=True, env=env)
            parsed = parse(log.read_text(), variant, repeat)
            if len(parsed) != len(inputs):
                raise RuntimeError("Unexpected number of cases")
            if repeat == 1:
                timed_out[variant] = {r["case"] for r in parsed if r["status"] == "timeout"}
            runs.extend(parsed)
            (dest / "lbp_stress_comparison_runs.json").write_text(json.dumps(data, indent=2)+"\n")
            counts = Counter(r["status"] for r in parsed)
            print(f"{variant} run {repeat}/{REPEATS}: {dict(counts)} in "
                  f"{time.monotonic()-started:.1f}s", flush=True)
            if hashes() != before:
                raise RuntimeError("Sources/data changed during the benchmark")
    for variant in variants:
        result = verify(roots[variant], fixed + variant_flags[variant], [SUITE], logdir, variant,
                        timeout=TIMEOUT)
        verification[variant] = {f"{s}:{c}": v for (s, c), v in result.items()}
        print(f"{variant} verification: {Counter(v['status'] for v in result.values())}, "
              f"{sum(1 for v in result.values() if v['valid'])} valid", flush=True)
    (dest / "lbp_stress_comparison_runs.json").write_text(json.dumps(data, indent=2)+"\n")
    write_report(data, dest)


if __name__ == "__main__":
    main()
